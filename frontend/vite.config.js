import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * إعدادات Vite (الأداة التي تشغّل الواجهة أثناء التطوير).
 *
 * أهم سطر هنا هو "proxy": الواجهة تعمل على المنفذ 5173 والخادم على 3001.
 * الـ proxy يجعل أي طلب يبدأ بـ /api يُمرَّر تلقائياً إلى الخادم،
 * فلا نحتاج كتابة العنوان الكامل ولا نواجه مشاكل الأمان بين المنفذين.
 */
export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    // host: true يجعل الواجهة تستمع على شبكة الواي فاي كلها وليس على هذا الجهاز فقط،
    // فيظهر في الطرفية رابط "Network" تفتحه من الجوال وهو على نفس الشبكة.
    host: true,
    // ملاحظة: لا نفتح المتصفح تلقائياً لأن ذلك يفشل على بعض الأنظمة.
    // بعد التشغيل افتح الرابط الذي يظهر في نافذة الطرفية بنفسك.
    proxy: {
      '/api': {
        target: 'http://localhost:3001',
        changeOrigin: true,
      },
    },
  },
});
